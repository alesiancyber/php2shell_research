#!/usr/bin/env python3
"""Export the case-study evidence from the Kusto emulator to CSV and to the site's Evidence page.
   export-evidence.py
Runs every block in kql/evidence.kql (each starts with "// --- out: <cve>/<name>") against database WinLab,
writes evidence/<cve>/<name>.csv, and regenerates evidence.md with every result as a table.
Re-running overwrites the files."""
import csv
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from kx import kusto  # noqa: E402

REPO = pathlib.Path(__file__).resolve().parent.parent
HEADINGS = {
    "iis-requests": "IIS request log (W3CIISLog)",
    "php-error-log": "PHP error log (PhpErrorLog_CL)",
    "php-event-log": "PHP in the Application event log (Event)",
    "worker-lifecycle": "FastCGI worker lifecycle (SecurityEvent, Sysmon)",
    "run-summary": "Run summary (detection query 0)",
    "reused-worker-fatals": "Detection B output",
}

PAGE_HEAD = """---
title: Evidence
nav_order: 3
---

# Evidence
{: .no_toc }

Every raw row behind the case studies, straight from the lab's Kusto tables (Sentinel schemas). Generated by
[`scripts/export-evidence.py`]({{ site.github.repository_url }}/blob/main/scripts/export-evidence.py) from the
queries in [`kql/evidence.kql`]({{ site.github.repository_url }}/blob/main/kql/evidence.kql); each table also
has a CSV download. All times are UTC.
{: .fs-5 .fw-300 }

<details open markdown="block"><summary>Contents</summary>{: .text-delta }
1. TOC
{:toc}
</details>
"""


def cell(v):
    s = "" if v is None else str(v)
    s = s.replace("|", "\\|").replace("\n", " ").replace("`", "'")
    # Paths, JSON and log lines go in code spans so markdown leaves backslashes and brackets alone.
    return f"`{s}`" if re.search(r"[\\\[\]<>*_]", s) else s


def main():
    text = (REPO / "kql" / "evidence.kql").read_text()
    page, cve = [PAGE_HEAD], None
    for name, block in re.findall(r"(?m)^// --- out: (\S+)\n(.*?)(?=^// --- out:|\Z)", text, re.S):
        lines = block.strip().splitlines()
        about = " ".join(l.lstrip("/ ").strip() for l in lines if l.lstrip().startswith("//"))
        csl = "\n".join(l for l in lines if not l.lstrip().startswith("//")).strip()
        ok, cols, rows = kusto(csl)
        if not ok:
            sys.exit(f"{name} failed: {rows}")
        out = REPO / "evidence" / f"{name}.csv"
        out.parent.mkdir(parents=True, exist_ok=True)
        with out.open("w", newline="") as f:
            w = csv.writer(f)
            w.writerow(cols)
            w.writerows(["" if v is None else v for v in r] for r in rows)
        print(f"{len(rows):4} rows  {out.relative_to(REPO)}")

        group, table = name.split("/", 1)
        if group != cve:
            cve = group
            page.append(f"\n## {group.upper()}\n\nCase study: [{group.upper()}](case-studies/{group}.html)\n")
        page.append(f"\n### {HEADINGS.get(table, table)}\n\n{about}\n")
        if rows:
            page.append("\n| " + " | ".join(cols) + " |\n| " + " | ".join("---" for _ in cols) + " |\n")
            page.extend("| " + " | ".join(cell(v) for v in r) + " |\n" for r in rows)
        else:
            page.append("\n**No rows.**\n")
        page.append(f"\n{len(rows)} rows · [CSV](evidence/{name}.csv)\n")
        page.append(f"\n<details markdown=\"block\"><summary>Query</summary>\n\n```kusto\n{csl}\n```\n</details>\n")
    (REPO / "evidence.md").write_text("".join(page))
    print("page      evidence.md")


if __name__ == "__main__":
    main()
